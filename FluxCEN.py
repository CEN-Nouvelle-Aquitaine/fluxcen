    def chargement_flux(self):
        """
        Main function to load layers from tableWidget_2 based on service type (WMS, WFS, PostGIS).
        """
        _, styles_couches = self.load_urls('config/yaml/links.yaml')

        if self.dlg.tableWidget_2.rowCount() == 0:
            log(
                "Aucun flux à charger dans la table de sélection.",
                Qgis.MessageLevel.Warning,
                True
            )    
            return

        for row in range(self.dlg.tableWidget_2.rowCount()):
            try:
                # Utilisation de la fonction de validation des données
                data = self.parse_table_row(row, styles_couches)
                if not data:
                    continue  # Si des données manquent, passer à la ligne suivante

                service, nom_couche, nom_technique, url, style_url = data

                # Gestion des types de service (WFS, WMS, PostGIS)
                if service.startswith("WMS"):
                    self.handle_wms_layer(row, nom_couche, nom_technique, url, style_url)
                elif service == "WFS":
                    self.handle_wfs_layer(row, nom_couche, nom_technique, url, style_url)
                elif service == "PostGIS":
                    self.handle_postgis_layer(row)

            except Exception as e:  # pylint: disable=broad-exception-caught
                log(
                    f"Erreur lors du chargement de la ligne: {row}, Erreur: {e}",
                    Qgis.MessageLevel.Warning
                )
                continue  # Passer à la ligne suivante en cas d'erreur


        # Vider le contenu de tableWidget_2
        self.dlg.tableWidget_2.clearContents()  # Efface les cellules existantes
        self.dlg.tableWidget_2.setRowCount(0)   # Réinitialise le nombre de lignes à 0

    def parse_table_row(self, row, styles_couches):
        """
        Extract relevant data from a given row in tableWidget_2.
        """
        cells = []
        for col in range(10):
            item = self.dlg.tableWidget_2.item(row, col)
            cells.append(item.text() if item is not None else "")

        flux = catalog.parse_table_row(cells)
        if flux is None:
            log("Données manquantes ou invalides dans la ligne : %s" % row,
                Qgis.MessageLevel.Warning)
            return None

        # URL du style si disponible : URL directe (concaténation) ou lien de
        # partage de dossier SharePoint (résolution en deux étapes via Graph).
        # Un échec de résolution ne bloque pas la couche : elle charge sans style.
        style_url = None
        if flux.style:
            try:
                style_url = self._style_url(styles_couches, flux.style)
            except Exception as exc:  # pylint: disable=broad-exception-caught
                log("Résolution du style « %s » impossible : %s" % (flux.style, exc),
                    Qgis.MessageLevel.Warning)

        return flux.service, flux.nom_couche, flux.nom_technique, flux.url, style_url


    def handle_wms_layer(self, row, nom_couche, nom_technique, url, style_url):
        """
        Handle WMS layer loading and apply authentication if necessary.
        """
        # Les couches du catalogue sont chargées sans authentification (FR-010),
        # sauf le service sécurisé du CEN qui reçoit une configuration adaptée
        # non web — jamais la configuration Microsoft (FR-012).
        authcfg_id = None
        if layer_builder.is_cen_secured_service(url):
            authcfg_id = self._select_service_authcfg()
            if not authcfg_id:
                # Pas de config adaptée : ne pas tenter la requête (couche vide
                # + fenêtre d'identification native de QGIS sinon)
                log(
                    f"Impossible de charger la couche : {nom_couche} | {nom_technique} "
                    "(authentification requise, aucune configuration adaptée).",
                    Qgis.MessageLevel.Critical,
                    True
                )
                return
        wms_layer_url = layer_builder.build_wms_uri(url, nom_technique, authcfg=authcfg_id)
        wms_layer = QgsRasterLayer(wms_layer_url, nom_couche, "wms")

        if wms_layer.isValid():
            QgsProject.instance().addMapLayer(wms_layer)
        else:
            log(
                f"Impossible de charger la couche : {nom_couche} | {nom_technique}.",
                Qgis.MessageLevel.Critical,
                True
            )

    def handle_wfs_layer(self, row, nom_couche, nom_technique, url, style_url):
        """
        Handle WFS layer loading and apply authentication if necessary.
        """
        # Les couches du catalogue sont chargées sans authentification (FR-010),
        # sauf le service sécurisé du CEN qui reçoit une configuration adaptée
        # non web — jamais la configuration Microsoft (FR-012).
        uri = QgsDataSourceUri()
        for key, value in layer_builder.build_wfs_uri_params(url, nom_technique).items():
            uri.setParam(key, value)
        if layer_builder.is_cen_secured_service(url):
            authcfg_id = self._select_service_authcfg()
            if not authcfg_id:
                # Pas de config adaptée : ne pas tenter la requête (couche vide
                # + fenêtre d'identification native de QGIS sinon)
                log(
                    f"Impossible de charger la couche : {nom_couche} | {nom_technique} "
                    "(authentification requise, aucune configuration adaptée).",
                    Qgis.MessageLevel.Critical,
                    True
                )
                return
            uri.setAuthConfigId(authcfg_id)
        wfs_layer = QgsVectorLayer(uri.uri(False), nom_couche, "WFS")

        if wfs_layer.isValid():
            QgsProject.instance().addMapLayer(wfs_layer)
            if style_url:
                self.apply_qml_style(wfs_layer, style_url)
        else:
            log(
                f"Impossible de charger la couche : {nom_couche} | {nom_technique}.",
                Qgis.MessageLevel.Critical,
                True
            )

    def handle_postgis_layer(self, row):
        """
        Handle PostGIS layer loading and apply authentication if necessary.
        """
        postgis_config = self.load_postgis_config('config/yaml/config_db.yaml')
        if not postgis_config:
            log(
                "Impossible de charger la configuration PostGIS depuis le fichier YAML.",
                Qgis.MessageLevel.Critical,
                True
            )
            return

        db_host = postgis_config['host']
        db_port = str(postgis_config['port'])
        db_name = self.dlg.tableWidget_2.item(row, 8).text()
        schema_name = self.dlg.tableWidget_2.item(row, 9).text()
        table_name = self.dlg.tableWidget_2.item(row, 3).text()

        if not (db_host and db_port and db_name and schema_name and table_name):
            log(
                "Des informations de connexion sont manquantes pour la base de données PostGIS.",
                Qgis.MessageLevel.Critical,
                True
            )
            return

        uri = QgsDataSourceUri()
        uri.setConnection(db_host, db_port, db_name, None, None)

        # Même mécanisme filtré que pour les couches WMS/WFS sécurisées (FR-011)
        authcfg_id = self._select_service_authcfg()
        if not authcfg_id:
            return  # Skip if authentication fails
        uri.setAuthConfigId(authcfg_id)

        uri.setDataSource(schema_name, table_name, "geom")

        layer = QgsVectorLayer(uri.uri(False), self.dlg.tableWidget_2.item(row, 2).text(), "postgres")
        if layer.isValid():
            QgsProject.instance().addMapLayer(layer)
        else:
            log(
                f"Échec de chargement de la couche PostGIS : {schema_name}, {table_name}",
                Qgis.MessageLevel.Critical,
                True
            )

    def filtre_dynamique(self, filter_text):

        for i in range(self.dlg.tableWidget.rowCount()):
            for j in range(self.dlg.tableWidget.columnCount()):
                item = self.dlg.tableWidget.item(i, j)
                match = filter_text.lower() not in item.text().lower()
                self.dlg.tableWidget.setRowHidden(i, match)
                if not match:
                    break
